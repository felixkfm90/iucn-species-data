import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { germanTaxonomyDisplayNames } from '../../species-explorer/taxonomy-display-names.mjs';

const target = new URL('../lib/domain/taxonomy_names.dart', import.meta.url);
const dartLiteral = value => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;

function mobileTaxonomyNames() {
  const lines = ['// Generated by mobile/tool/taxonomy-names.mjs from the Arten-Explorer taxonomy names.',
    'const germanTaxonomyNames = <String, Map<String, String>>{'];
  for (const [rank, names] of Object.entries(germanTaxonomyDisplayNames())) {
    const entries = Object.entries(names).sort(([a], [b]) => a.localeCompare(b, 'en'))
      .map(([name, label]) => `${dartLiteral(name.toLowerCase())}: ${dartLiteral(label)}`);
    const compact = `  ${dartLiteral(rank)}: {${entries[0]}},`;
    if (entries.length === 1 && compact.length <= 80) {
      lines.push(compact);
      continue;
    }
    lines.push(`  ${dartLiteral(rank)}: {`);
    for (const entry of entries) lines.push(`    ${entry},`);
    lines.push('  },');
  }
  return `${lines.join('\n')}\n};\n`;
}

export function checkMobileTaxonomyNames() {
  assert.equal(readFileSync(target, 'utf8').replaceAll('\r\n', '\n'), mobileTaxonomyNames(),
    'Die deutschen Taxonomienamen der App müssen aus der Arten-Explorer-Tabelle erzeugt werden.');
}

export function writeMobileTaxonomyNames() {
  writeFileSync(target, mobileTaxonomyNames());
}

if (import.meta.main) {
  if (process.argv.includes('--check')) checkMobileTaxonomyNames();
  else writeMobileTaxonomyNames();
}
